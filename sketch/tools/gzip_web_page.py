# PlatformIO pre-build step: gzip web/index.html into include/web_page_gz.h,
# so the firmware stores the page at about a quarter of its size and serves it
# gzipped. Edit web/index.html, not the generated header.
# (Keep the words "coding" + ":" out of the first two lines: Python would read
# them as a source-encoding declaration.)
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

project = env.subst("$PROJECT_DIR")  # noqa: F821
src = os.path.join(project, "web", "index.html")
dst = os.path.join(project, "include", "web_page_gz.h")

with open(src, "rb") as f:
    data = gzip.compress(f.read(), compresslevel=9, mtime=0)

lines = ["// Generated by tools/gzip_web_page.py from web/index.html. Do not edit.",
         "#pragma once",
         "#include <Arduino.h>",
         "static const uint8_t WEB_PAGE_GZ[] PROGMEM = {"]
for i in range(0, len(data), 24):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
lines += ["};", f"static const size_t WEB_PAGE_GZ_LEN = {len(data)};", ""]
text = "\n".join(lines)

old = open(dst).read() if os.path.exists(dst) else None
if text != old:  # don't touch the file (and trigger rebuilds) when unchanged
    with open(dst, "w", newline="\n") as f:
        f.write(text)
