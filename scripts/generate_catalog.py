#!/usr/bin/env python3
"""
scripts/generate_catalog.py
Automatically synchronizes TuneBar firmware releases catalog between git,
releases/firmware_catalog.json, and sketch/include/generated_catalog.h.
"""

import os
import sys
import json
import subprocess
import datetime

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG_JSON_PATH = os.path.join(ROOT_DIR, "releases", "firmware_catalog.json")
GENERATED_H_PATH = os.path.join(ROOT_DIR, "sketch", "include", "generated_catalog.h")
RELEASES_BIN_DIR = os.path.join(ROOT_DIR, "releases", "bin")

def get_git_output(args):
    try:
        res = subprocess.run(
            ["git"] + args,
            cwd=ROOT_DIR,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=True
        )
        return res.stdout.strip()
    except Exception:
        return None

def main():
    # 1. Read existing catalog JSON
    existing_catalog = {"repo_id": "official", "releases": []}
    if os.path.exists(CATALOG_JSON_PATH):
        try:
            with open(CATALOG_JSON_PATH, "r", encoding="utf-8") as f:
                existing_catalog = json.load(f)
        except Exception as e:
            print(f"[WARN] Failed to parse {CATALOG_JSON_PATH}: {e}")

    releases = existing_catalog.get("releases", [])

    # 2. Get current version from git tag or describe
    tag = get_git_output(["describe", "--tags", "--abbrev=0"])
    cur_ver = "1.2.8"
    if tag:
        t_clean = tag.lstrip("v")
        parts = t_clean.split(".")
        if len(parts) >= 3 and all(p.isdigit() for p in parts[:3]):
            if tuple(int(p) for p in parts[:3]) >= (1, 2, 8):
                cur_ver = f"{parts[0]}.{parts[1]}.{parts[2]}"
    commit_count = get_git_output(["rev-list", "--count", "HEAD"])
    build_num = int(commit_count) if commit_count and commit_count.isdigit() else 22
    now_date = datetime.date.today().strftime("%b %d, %Y")

    # Check binary size if present
    bin_name = f"firmware-v{cur_ver}.bin"
    bin_path = os.path.join(RELEASES_BIN_DIR, bin_name)
    bin_size = 4283408 # default fallback (~4.08MB)
    if os.path.exists(bin_path):
        bin_size = os.path.getsize(bin_path)

    # 3. Check if cur_ver is in catalog, if not prepend it
    found = False
    for r in releases:
        if r.get("version") == cur_ver or r.get("version") == f"v{cur_ver}":
            found = True
            r["build"] = build_num
            r["size"] = bin_size
            break

    if not found:
        new_entry = {
            "version": cur_ver,
            "type": "patch",
            "build": build_num,
            "date": now_date,
            "title": f"TuneBar v{cur_ver} Firmware Release",
            "changelog": "• Automated multi-tenant telemetry and device registration guard.\n• 4-Row 3-State IMU posture panel with active/inverted tracking.\n• High-precision shelf inclinometer and uphill air bubble physics.\n• Dynamic isometric chassis diagram in calibration wizard.\n• Clock breathing interaction wake fix.",
            "url": f"https://raw.githubusercontent.com/rahulraj80/TuneBar/main/releases/bin/{bin_name}",
            "size": bin_size
        }
        releases.insert(0, new_entry)

    # Sort releases by version descending (semver tuple)
    def parse_semver(v_str):
        v = v_str.lstrip("v")
        parts = v.split(".")
        try:
            return [int(p) for p in parts[:3]]
        except Exception:
            return [0, 0, 0]

    releases.sort(key=lambda r: parse_semver(r.get("version", "0.0.0")), reverse=True)
    existing_catalog["releases"] = releases

    # 4. Save updated catalog JSON
    os.makedirs(os.path.dirname(CATALOG_JSON_PATH), exist_ok=True)
    with open(CATALOG_JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(existing_catalog, f, indent=2)
    print(f"[OK] Updated {CATALOG_JSON_PATH} with {len(releases)} releases.")

    # 5. Generate C header sketch/include/generated_catalog.h
    h_lines = [
        "#pragma once",
        "// AUTO-GENERATED BY scripts/generate_catalog.py - DO NOT EDIT MANUALLY",
        "",
        '#include <Arduino.h>',
        "",
        "struct CatalogItem {",
        "  char version[16];",
        "  char type_name[12];",
        "  uint32_t color_hex;",
        "  char date[24];",
        "  char size_str[16];",
        "  char changelog[1024];",
        "  char bin_url[256];",
        "  uint32_t size_bytes;",
        "};",
        "",
        f"#define GENERATED_CATALOG_COUNT {len(releases)}",
        "",
        f"static const CatalogItem s_generated_catalog[{len(releases)}] = {{"
    ]

    for idx, r in enumerate(releases):
        v = r.get("version", "1.0.0")
        v_str = v if v.startswith("v") else f"v{v}"
        t_type = r.get("type", "patch").upper()
        if t_type == "MAJOR":
            color = "0xB388FF"
        elif t_type == "MINOR":
            color = "0x00B0FF"
        else:
            color = "0x00FF88"

        date_str = r.get("date", "Oct 12, 2026")
        sz_bytes = r.get("size", 4280000)
        sz_mb = f"{sz_bytes / (1024*1024):.2f} MB" if sz_bytes > 0 else "4.08 MB"
        cl = r.get("changelog", "").replace("\\n", "\n").replace('"', '\\"').replace('\n', '\\n"\n    "')
        url = r.get("url", f"https://raw.githubusercontent.com/rahulraj80/TuneBar/main/releases/bin/firmware-{v_str}.bin")

        h_lines.append(f"  // [{idx}] {v_str}")
        h_lines.append("  {")
        h_lines.append(f'    "{v_str}", "{t_type}", {color}, "{date_str}", "{sz_mb}",')
        h_lines.append(f'    "{cl}",')
        h_lines.append(f'    "{url}",')
        h_lines.append(f'    {sz_bytes}')
        h_lines.append("  }" + ("," if idx < len(releases) - 1 else ""))

    h_lines.append("};")
    h_lines.append("")

    # Helper function to generate JSON string for web_remote.cpp
    h_lines.append("static inline String get_generated_catalog_json(void) {")
    h_lines.append('  String j = "{\\\"repo_id\\\":\\\"official\\\",\\\"releases\\\":[";')
    for idx, r in enumerate(releases):
        v = r.get("version", "1.0.0")
        v_str = v.lstrip("v")
        t_type = r.get("type", "patch").lower()
        b_num = r.get("build", 20)
        d_str = r.get("date", "")
        sz_bytes = r.get("size", 4280000)
        sz_mb = f"{sz_bytes / (1024*1024):.2f} MB"
        cl_clean = r.get("changelog", "").replace("\n", " ").replace('"', "'")
        u_str = r.get("url", "")
        comma_str = "," if idx < len(releases) - 1 else ""
        h_lines.append(f'  j += "{{\\\"version\\\":\\\"{v_str}\\\",\\\"type\\\":\\\"{t_type}\\\",\\\"build\\\":{b_num},\\\"date\\\":\\\"{d_str}\\\",\\\"size\\\":\\\"{sz_mb}\\\",\\\"size_bytes\\\":{sz_bytes},\\\"changelog\\\":\\\"{cl_clean}\\\",\\\"url\\\":\\\"{u_str}\\\"}}{comma_str}";')
    h_lines.append('  j += "]}";')
    h_lines.append("  return j;")
    h_lines.append("}")
    h_lines.append("")

    os.makedirs(os.path.dirname(GENERATED_H_PATH), exist_ok=True)
    with open(GENERATED_H_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(h_lines))
    print(f"[OK] Generated {GENERATED_H_PATH} with {len(releases)} releases.")

if __name__ == "__main__":
    main()
