#!/usr/bin/env python3
import subprocess
import os
import sys
import datetime

# Root directory of TuneBar repo
ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSION_H_PATH = os.path.join(ROOT_DIR, "sketch", "include", "version.h")

def get_git_output(args):
    try:
        res = subprocess.run(
            ["git"] + args,
            cwd=ROOT_DIR,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=True
        )
        return res.stdout.strip()
    except Exception:
        return None

def main():
    # Base version: major.minor.patch
    base_ver = "1.2.9"
    
    # Try reading from latest git tag if present
    tag = get_git_output(["describe", "--tags", "--abbrev=0"])
    if tag:
        tag_clean = tag.lstrip("v")
        parts = tag_clean.split(".")
        if len(parts) >= 3 and all(p.isdigit() for p in parts[:3]):
            t_tuple = tuple(int(p) for p in parts[:3])
            if t_tuple >= (1, 2, 9):
                base_ver = f"{parts[0]}.{parts[1]}.{parts[2]}"

    major, minor, patch = base_ver.split(".")[:3]
    
    # Commit count
    commit_count = get_git_output(["rev-list", "--count", "HEAD"])
    if not commit_count or not commit_count.isdigit():
        commit_count = "48"
        
    # Short git hash
    git_hash = get_git_output(["rev-parse", "--short", "HEAD"])
    if not git_hash:
        git_hash = "local"

    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    header_content = f"""#pragma once
// AUTO-GENERATED BY scripts/generate_version.py - DO NOT EDIT MANUALLY

#define TUNEBAR_VERSION_MAJOR {int(major)}
#define TUNEBAR_VERSION_MINOR {int(minor)}
#define TUNEBAR_VERSION_PATCH {int(patch)}
#define TUNEBAR_VERSION_STR   "{base_ver}"
#define TUNEBAR_BUILD_NUM     {int(commit_count)}
#define TUNEBAR_GIT_HASH      "{git_hash}"
#define TUNEBAR_BUILD_DATE    "{now_str}"
"""

    os.makedirs(os.path.dirname(VERSION_H_PATH), exist_ok=True)
    with open(VERSION_H_PATH, "w", encoding="utf-8") as f:
        f.write(header_content)

    print(f"Generated {VERSION_H_PATH}: v{base_ver} (Build #{commit_count} - {git_hash})")

if __name__ == "__main__":
    main()
