#!/usr/bin/env python3
"""
release.py - Automated Semantic Versioning, Git Tagging, and Release Pipeline for TuneBar.

Enforces strict semantic versioning:
  python release.py patch "Fix description"    -> increments patch (X.Y.Z+1)
  python release.py minor "Feature description"  -> increments minor (X.Y+1.0)
  python release.py major "Major architecture"  -> increments major (X+1.0.0)

Aliases:
  patch / fix / correction
  minor / feature / feat
  major / breaking
"""

import sys
import os
import subprocess
import json
import datetime

ROOT_DIR = os.path.dirname(os.path.abspath(__file__))
os.chdir(ROOT_DIR)

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
if hasattr(sys.stderr, 'reconfigure'):
    sys.stderr.reconfigure(encoding='utf-8', errors='replace')

def run_cmd(cmd_list, check=True):
    cmd_str = " ".join(cmd_list)
    print(f">> {cmd_str}", flush=True)
    res = subprocess.run(
        cmd_list,
        cwd=ROOT_DIR,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
        errors="replace"
    )
    if check and res.returncode != 0:
        print(f"[ERROR] Command failed with code {res.returncode}:\n{res.stderr}", flush=True)
        sys.exit(res.returncode)
    return res.stdout.strip()

def get_latest_tag():
    try:
        tag = run_cmd(["git", "describe", "--tags", "--abbrev=0"], check=False)
        if tag and tag.startswith("v"):
            return tag
    except Exception:
        pass
    # Fallback to listing all tags
    try:
        tags_raw = run_cmd(["git", "tag", "-l"], check=False)
        tags = [t.strip() for t in tags_raw.splitlines() if t.strip().startswith("v")]
        if tags:
            # Sort by semver tuples
            def tag_sort_key(t):
                parts = t.lstrip("v").split(".")
                return tuple(int(p) if p.isdigit() else 0 for p in parts[:3])
            tags.sort(key=tag_sort_key)
            return tags[-1]
    except Exception:
        pass
    return "v1.2.9"

def parse_semver(tag_str):
    clean = tag_str.lstrip("v")
    parts = clean.split(".")
    major = int(parts[0]) if len(parts) > 0 and parts[0].isdigit() else 1
    minor = int(parts[1]) if len(parts) > 1 and parts[1].isdigit() else 0
    patch = int(parts[2]) if len(parts) > 2 and parts[2].isdigit() else 0
    return major, minor, patch

def compute_next_version(bump_type, major, minor, patch):
    bump_lower = bump_type.lower()
    if bump_lower in ["major", "breaking"]:
        return major + 1, 0, 0, "major"
    elif bump_lower in ["minor", "feature", "feat"]:
        return major, minor + 1, 0, "minor"
    elif bump_lower in ["patch", "fix", "correction"]:
        return major, minor, patch + 1, "patch"
    else:
        print(f"[ERROR] Invalid bump type '{bump_type}'. Choose from: major, minor/feature, patch/fix", flush=True)
        sys.exit(1)

def update_version_header(next_ver_str, major, minor, patch, build_num, git_hash):
    version_h_path = os.path.join(ROOT_DIR, "sketch", "include", "version.h")
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    content = f"""#pragma once
// AUTO-GENERATED BY release.py - DO NOT EDIT MANUALLY

#define TUNEBAR_VERSION_MAJOR {major}
#define TUNEBAR_VERSION_MINOR {minor}
#define TUNEBAR_VERSION_PATCH {patch}
#define TUNEBAR_VERSION_STR   "{next_ver_str}"
#define TUNEBAR_BUILD_NUM     {build_num}
#define TUNEBAR_GIT_HASH      "{git_hash}"
#define TUNEBAR_BUILD_DATE    "{now_str}"
"""
    with open(version_h_path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[OK] Generated {version_h_path}: v{next_ver_str} (Build #{build_num})", flush=True)

def update_catalog(next_ver_str, rel_type, message, build_num):
    catalog_json_path = os.path.join(ROOT_DIR, "releases", "firmware_catalog.json")
    
    catalog_data = {"repo_id": "official", "releases": []}
    if os.path.exists(catalog_json_path):
        try:
            with open(catalog_json_path, "r", encoding="utf-8") as f:
                catalog_data = json.load(f)
        except Exception as e:
            print(f"[WARN] Failed to read {catalog_json_path}: {e}")
            
    releases = catalog_data.get("releases", [])
    now_date = datetime.date.today().strftime("%b %d, %Y")
    
    # Check if this version entry already exists
    entry = None
    for r in releases:
        if r.get("version") == next_ver_str:
            entry = r
            break
            
    changelog_bullet = f"• {message}"
    if entry:
        entry["type"] = rel_type
        entry["build"] = build_num
        entry["date"] = now_date
        entry["title"] = f"TuneBar v{next_ver_str}: {message}"
        if message not in entry.get("changelog", ""):
            entry["changelog"] = changelog_bullet + "\n" + entry.get("changelog", "")
    else:
        new_entry = {
            "version": next_ver_str,
            "type": rel_type,
            "build": build_num,
            "date": now_date,
            "title": f"DeskBar AI v{next_ver_str}: {message}",
            "changelog": changelog_bullet,
            "url": f"https://raw.githubusercontent.com/rahulraj80/DeskBar-AI/main/releases/bin/firmware-v{next_ver_str}.bin",
            "size": 4200000
        }
        releases.insert(0, new_entry)
        
    catalog_data["releases"] = releases
    with open(catalog_json_path, "w", encoding="utf-8") as f:
        json.dump(catalog_data, f, indent=2)
    print(f"[OK] Updated {catalog_json_path} with {len(releases)} releases.", flush=True)

    # Use scripts/generate_catalog.py to keep struct layout & get_generated_catalog_json identical
    gen_cat = os.path.join(ROOT_DIR, "scripts", "generate_catalog.py")
    subprocess.run([sys.executable, gen_cat], check=True)

def main():
    if len(sys.argv) < 3:
        print("Usage: python release.py <patch|minor|major> \"Commit & Release Description\" [--no-build] [--no-push]")
        sys.exit(1)

    bump_arg = sys.argv[1].strip()
    message = sys.argv[2].strip().rstrip('\\').strip().replace('"', "'")
    no_build = "--no-build" in sys.argv
    no_push = "--no-push" in sys.argv

    # 1. Determine latest version from tag
    cur_tag = get_latest_tag()
    major, minor, patch = parse_semver(cur_tag)
    print(f"Current Latest Tag: {cur_tag} (Parsed: {major}.{minor}.{patch})", flush=True)

    # 2. Compute next semantic version
    next_major, next_minor, next_patch, rel_type = compute_next_version(bump_arg, major, minor, patch)
    next_ver_str = f"{next_major}.{next_minor}.{next_patch}"
    next_tag = f"v{next_ver_str}"
    print(f"Target Release: {next_tag} ({rel_type.upper()})", flush=True)

    # STRICT UNIQUENESS GUARD: Ensure this tag does not already exist in git or catalog
    existing_tags_raw = run_cmd(["git", "tag", "-l"], check=False)
    existing_tags = [t.strip() for t in existing_tags_raw.splitlines() if t.strip()]
    if next_tag in existing_tags:
        print(f"[FATAL ERROR] Tag {next_tag} already exists in Git history! Duplicate version numbers are strictly prohibited.", flush=True)
        print("Aborting release to protect OTA pull uniqueness.", flush=True)
        sys.exit(1)

    # 3. Calculate next build number (commit count + 1)
    commit_count_str = run_cmd(["git", "rev-list", "--count", "HEAD"])
    build_num = int(commit_count_str) + 1 if commit_count_str.isdigit() else 25

    # Temporary placeholder git hash (will match HEAD commit after)
    head_hash = run_cmd(["git", "rev-parse", "--short", "HEAD"])

    # 4. Generate version.h, catalog.json, and generated_catalog.h
    update_version_header(next_ver_str, next_major, next_minor, next_patch, build_num, head_hash)
    update_catalog(next_ver_str, rel_type, message, build_num)

    # 5. Git Add & Commit
    commit_msg = f"{rel_type}({next_tag}): {message}"
    run_cmd(["git", "add", "-A"])
    run_cmd([
        "git", "commit", "-m", commit_msg,
        "--author=Rahul_Azure <rahul.raj@gmail.com>"
    ])

    # Update version.h with real git hash if desired
    real_hash = run_cmd(["git", "rev-parse", "--short", "HEAD"])
    update_version_header(next_ver_str, next_major, next_minor, next_patch, build_num, real_hash)
    run_cmd(["git", "add", "sketch/include/version.h"])
    run_cmd(["git", "commit", "--amend", "--no-edit"])

    # 6. Create Git Tag
    print(f"Creating Git Tag: {next_tag}", flush=True)
    run_cmd(["git", "tag", "-a", next_tag, "-m", f"Release {next_tag}: {message}"])

    # 7. Push Commits and Tags to Remote BEFORE building
    if not no_push:
        print("--- Pushing commits and tags to GitHub origin/main ---", flush=True)
        run_cmd(["git", "push", "origin", "main", "--tags"])

    # 8. Remote Build via PlatformIO on server if not skipped
    if not no_build:
        print(f"--- Triggering Remote Build for {next_tag} on auto ---", flush=True)
        sync_and_build_path = os.path.join(ROOT_DIR, "scripts", "sync_and_build.py")
        build_code = subprocess.run([sys.executable, sync_and_build_path, "--no-push"]).returncode
        if build_code != 0:
            print("[ERROR] Build failed! Aborting release pipeline.", flush=True)
            sys.exit(build_code)

    print(f"\n=======================================================", flush=True)
    print(f" SUCCESS: TuneBar {next_tag} (Build #{build_num}) released & compiled!", flush=True)
    print(f" Binary: build_phase1/firmware.bin", flush=True)
    print(f" Next steps:", flush=True)
    print(f"   1. Flash to device: python -m esptool --chip esp32s3 -p COM11 -b 921600 --before default-reset --after hard-reset write_flash -z --flash_mode dio --flash_freq 80m --flash_size detect 0x0000 build_phase1/bootloader.bin 0x8000 build_phase1/partitions.bin 0xe000 build_phase1/boot_app0.bin 0x10000 build_phase1/firmware.bin", flush=True)
    print(f"   2. Verify device features and screen behavior.", flush=True)
    print(f"   3. After testing, promote to OTA (retaining top 2 versions in git):", flush=True)
    print(f"      python scripts/publish_ota.py {next_tag}", flush=True)
    print(f"=======================================================\n", flush=True)

if __name__ == "__main__":
    main()
